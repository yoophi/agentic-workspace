//! HTTP retry policy consumes the same operation kinds as authorization and OpenAPI.
use std::collections::BTreeMap;
use workbench_protocol::{operations::OPERATIONS, OperationKind};

fn main() {
    println!("// Generated by workbench-protocol/export_operation_kinds. Do not edit by hand.");
    println!("import type {{ OperationId }} from \"./operation-map\";");
    // Deterministic ordering keeps review diffs local when adding an operation.
    let kinds: BTreeMap<_, _> = OPERATIONS
        .iter()
        .map(|spec| (spec.id.as_str(), spec.kind))
        .collect();
    println!("export type OperationKind = \"query\" | \"command\";\n");
    println!("export const OPERATION_KINDS: Record<OperationId, OperationKind> = {{");
    for (name, kind) in kinds {
        let kind = match kind {
            OperationKind::Query => "query",
            OperationKind::Command => "command",
        };
        println!("  \"{name}\": \"{kind}\",");
    }
    println!("}};");
    println!("\nexport function isQueryOperation(operation: OperationId): boolean {{");
    println!("  return OPERATION_KINDS[operation] === \"query\";");
    println!("}}");
}
